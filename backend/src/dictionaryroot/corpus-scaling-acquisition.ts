export function serializeArtifact(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

export async function generateAcquisitionArtifacts(outputDirectory: string): Promise<void> {
  await mkdir(outputDirectory, { recursive: true });
  await Promise.all([
    writeFile(path.join(outputDirectory, "candidate-sources.json"), serializeArtifact(CANDIDATE_SOURCES), "utf8"),
    writeFile(path.join(outputDirectory, "feasibility-report.json"), serializeArtifact(FEASIBILITY_REPORT), "utf8"),
  ]);
}
